// backend/crypto_soft.h -- shared SOFTWARE reference for the crypto op face (AES round
// primitives + carryless multiply), factored out of backend/scalar.h so ALL five backends
// can reuse ONE copy of the 512-byte S-box tables + GF(2^8) logic.
//
// WHY a shared header: AES-NI (x86) / PMULL (ARM) are OPTIONAL ISA extensions ORTHOGONAL to
// the SSE4.2/AVX2/NEON tier this library's variant DLLs target -- GCC/Clang need explicit
// `-maes -mpclmul` (x86) or `+crypto` (ARM), which the base variants do NOT carry. When the
// hardware instruction is absent the backend MUST still satisfy the op contract (base
// library: the API surface is complete regardless of codegen flags), so it falls back to
// this software floor. Duplicating the 256-byte S-box + inverse across sse4/avx2/avx512/neon
// /scalar would be 5x table bloat; one header keeps a single source of truth.
//
// Byte-level cores operate on a 16-byte AES state in AES-NI byte order (column-major, lane 0
// byte at s[0]). This EXACTLY matches _mm_aesenc_si128 and vaesmcq_u8(vaeseq_u8(...)) so the
// software fallback is bit-identical to the hardware paths on every backend. The public
// Vec<T,N> wrappers (in each backend header) memcpy the vector to `s`, call these, memcpy
// back -- see backend/scalar.h for the reference wrapping.

