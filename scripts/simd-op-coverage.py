#!/usr/bin/env python3
"""Validate SIMD route configuration and generate its C++ headers.

The operation list, provider selections and compiler/ISA exceptions are product
configuration. Generation checks identifiers, complete default routes, selector
overlaps and locked dependency revisions using the current checkout.
"""

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
OPERATION_ROUTES = ROOT / "scripts/simd-op-routing.json"
FAMILY_ROUTES = ROOT / "scripts/simd-family-routing.json"
PROVIDER_MANIFEST = ROOT / "include/hyle/simd/provider/operation_manifest.h"
PROVIDER_ROUTES = ROOT / "include/hyle/simd/provider/routes_generated.h"


def operation_names(document):
    rows = document.get("operations")
    if not isinstance(rows, list) or not rows:
        raise ValueError("operation configuration must be a non-empty array")
    names = [row.get("name") if isinstance(row, dict) else None for row in rows]
    if any(not isinstance(name, str) or
           re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name) is None for name in names):
        raise ValueError("operation configuration contains invalid C++ identifiers")
    if len(names) != len(set(names)):
        raise ValueError("operation configuration contains duplicate names")
    return names


def render_provider_operation_manifest(document):
    names = operation_names(document)
    payload = json.dumps(names, separators=(",", ":")).encode("utf-8")
    digest = hashlib.sha256(payload).hexdigest()
    lines = [
        "/* SPDX-License-Identifier: LicenseRef-HYLE-Proprietary */",
        "#pragma once", "",
        "// Generated by scripts/simd-op-coverage.py from simd-op-routing.json.",
        "// The digest covers the ordered operation names. Do not hand-edit.",
        f'#define HYLE_SIMD_OPERATION_INVENTORY_SHA256 "{digest}"',
        f"#define HYLE_SIMD_OPERATION_COUNT {len(names)}",
        "#define HYLE_SIMD_OPERATION_LIST(X) " + chr(92),
    ]
    for index, name in enumerate(names):
        lines.append(f"  X({name})" + (" " + chr(92) if index + 1 != len(names) else ""))
    return "\n".join(lines) + "\n"


_ROUTE_CPP = {
    ("KEEP_HYLE", "HYLE"): ("Provider::kHyle", "Decision::kKeepHyle"),
    ("ROUTE_HIGHWAY", "HIGHWAY"): (
        "Provider::kHighway", "Decision::kRouteHighway"),
    ("ROUTE_XSIMD", "XSIMD"): ("Provider::kXsimd", "Decision::kRouteXsimd"),
    ("REMOVE_REDUNDANT", "COMPOSITION"): (
        "Provider::kNone", "Decision::kRemoveRedundant"),
    ("REMOVE_REDUNDANT", "NONE"): (
        "Provider::kNone", "Decision::kRemoveRedundant"),
}

_TYPE_CPP = {
    "i8": "std::int8_t", "u8": "std::uint8_t",
    "i16": "std::int16_t", "u16": "std::uint16_t",
    "i32": "std::int32_t", "u32": "std::uint32_t",
    "i64": "std::int64_t", "u64": "std::uint64_t",
    "f32": "float", "f64": "double",
}

_TARGET_CPP = {
    "SCALAR": "KernelTarget::kScalar", "SSE4": "KernelTarget::kSse4",
    "AVX2": "KernelTarget::kAvx2", "AVX512": "KernelTarget::kAvx512",
    "NEON": "KernelTarget::kNeon", "SVE": "KernelTarget::kSve", "RVV": "KernelTarget::kRvv",
}

_COMPILER_CPP = {
    "MSVC": "Compiler::kMsvc", "CLANG_CL": "Compiler::kClangCl",
    "CLANG": "Compiler::kClang", "APPLE_CLANG": "Compiler::kAppleClang",
    "GCC": "Compiler::kGcc", "OTHER": "Compiler::kOther",
}


def _route_cpp(decision, provider):
    key = (decision, provider)
    if key not in _ROUTE_CPP:
        raise RuntimeError(f"cannot generate terminal provider route {key}")
    return _ROUTE_CPP[key]


def _variant_cpp(selector):
    variant = selector.get("variant", {})
    kind = variant.get("kind")
    if kind == "ANY":
        if variant.get("contract_tags", []):
            raise RuntimeError("ANY provider route has unsupported contract tags")
        return "AnyVariant"
    if kind == "LANE":
        lane = variant.get("lane")
        if lane not in _TYPE_CPP:
            raise RuntimeError(f"provider route cannot express lane type {lane!r}")
        if variant.get("contract_tags", []):
            raise RuntimeError("LANE provider route has unsupported contract tags")
        return f"LaneVariant<{_TYPE_CPP[lane]}>"
    if kind == "CONVERSION":
        source = variant.get("from")
        destination = variant.get("to")
        if source not in _TYPE_CPP or destination not in _TYPE_CPP:
            raise RuntimeError("provider conversion route has unsupported lane types")
        tags = variant.get("contract_tags", [])
        if tags == []:
            contract = "ConversionContract::kDefault"
        elif tags == ["two-input-saturating"]:
            contract = "ConversionContract::kTwoInputSaturating"
        else:
            raise RuntimeError(f"provider conversion route has unsupported tags {tags}")
        return (
            f"ConversionVariant<{_TYPE_CPP[source]}, {_TYPE_CPP[destination]}, "
            f"{contract}>")
    if kind == "INVARIANT_DIVISOR":
        lane = variant.get("lane")
        if lane not in _TYPE_CPP:
            raise RuntimeError(f"provider invariant route cannot express lane type {lane!r}")
        if variant.get("contract_tags", []) != ["reusable-precomputed-divisor"]:
            raise RuntimeError("provider invariant route lacks its reusable-divisor contract")
        return f"InvariantDivisorVariant<{_TYPE_CPP[lane]}>"
    raise RuntimeError(f"provider route has unsupported selector kind {kind!r}")


def _render_default_route(key, decision, provider):
    provider_cpp, decision_cpp = _route_cpp(decision, provider)
    return [
        "template <typename Variant, KernelTarget kTarget, Compiler kCompiler,",
        "          std::uint32_t kCompilerVersion>",
        f"struct RouteFor<RouteKey<{key}>, Variant, kTarget, kCompiler, kCompilerVersion> final {{",
        f"  inline static constexpr Route value{{{provider_cpp}, {decision_cpp}}};",
        "};",
        "",
    ]


def _render_exact_routes(key, route):
    selector = route.get("selector")
    if not isinstance(selector, dict):
        raise RuntimeError(f"exact provider route {key} lacks a selector")
    variant_cpp = _variant_cpp(selector)
    provider_cpp, decision_cpp = _route_cpp(
        route.get("decision"), route.get("provider"))
    lines = []
    for target in selector.get("runtime_targets", []):
        if target not in _TARGET_CPP:
            raise RuntimeError(f"provider route has unsupported target {target!r}")
        for compiler_range in selector.get("compiler_ranges", []):
            compiler = compiler_range.get("kind")
            if compiler not in _COMPILER_CPP:
                raise RuntimeError(f"provider route has unsupported compiler {compiler!r}")
            minimum = compiler_range.get("min")
            maximum = compiler_range.get("max")
            if not isinstance(minimum, int) or not isinstance(maximum, int):
                raise RuntimeError("provider route compiler range is not integral")
            lines.extend([
                "template <std::uint32_t kCompilerVersion>",
                f"  requires (kCompilerVersion >= {minimum}u &&",
                f"            kCompilerVersion <= {maximum}u)",
                f"struct RouteFor<RouteKey<{key}>, {variant_cpp}, {_TARGET_CPP[target]},",
                f"                {_COMPILER_CPP[compiler]}, kCompilerVersion> final {{",
                f"  inline static constexpr Route value{{{provider_cpp}, {decision_cpp}}};",
                "};",
                "",
            ])
    if not lines:
        raise RuntimeError(f"exact provider route {key} expands to no specialization")
    return lines


def render_provider_routes(document, family_path):
    """Generate compile-time routes from operation and family configuration."""
    with open(family_path, encoding="utf-8") as src:
        families = json.load(src)
    if families.get("schema") != "hyle.simd.family-routing/v2":
        raise RuntimeError("SIMD family route configuration has an unsupported schema")
    expected_revisions = {
        provider: document.get("provider_revisions", {}).get(provider)
        for provider in ("HIGHWAY", "XSIMD")
    }
    if families.get("provider_revisions") != expected_revisions:
        raise RuntimeError("SIMD family routes do not match locked provider revisions")
    family_rows = families.get("families")
    if not isinstance(family_rows, list) or not family_rows:
        raise RuntimeError("SIMD family route configuration is empty")
    family_names = [row.get("name") for row in family_rows]
    if len(family_names) != len(set(family_names)) or any(
            not isinstance(name, str) or
            re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name) is None
            for name in family_names):
        raise RuntimeError("SIMD family routes contain invalid or duplicate names")

    lines = [
        "/* SPDX-License-Identifier: LicenseRef-HYLE-Proprietary */",
        "#pragma once",
        "",
        "// Generated by scripts/simd-op-coverage.py from SIMD operation",
        "// and family route configuration. Include only from route.h after",
        "// the RouteFor/RouteKey primary templates; do not hand-edit.",
        "",
        "enum class Family : std::uint8_t {",
    ]
    lines.extend(f"  k{name}," for name in family_names)
    lines.extend(["};", ""])

    for operation in document.get("operations", []):
        name = operation.get("name")
        routes = operation.get("routes", [])
        defaults = [route for route in routes if "selector" not in route]
        if not defaults:
            raise RuntimeError(f"{name}: terminal provider routes lack a default remainder")
        default_pairs = {
            (route.get("decision"), route.get("provider")) for route in defaults
        }
        if len(default_pairs) != 1:
            raise RuntimeError(f"{name}: default provider routes are not one terminal decision")
        decision, provider = next(iter(default_pairs))
        key = f"Operation::k{name}"
        lines.extend(_render_default_route(key, decision, provider))
        for route in routes:
            if "selector" in route:
                lines.extend(_render_exact_routes(key, route))

    for family in family_rows:
        name = family["name"]
        default = family.get("default", {})
        key = f"Family::k{name}"
        lines.extend(_render_default_route(
            key, default.get("decision"), default.get("provider")))
        exceptions = family.get("exceptions", [])
        if not isinstance(exceptions, list):
            raise RuntimeError(f"family {name} exceptions must be an array")
        for route in exceptions:
            lines.extend(_render_exact_routes(key, route))
    return "\n".join(lines)


def validate_provider_routes(document, family_path, generated_path):
    try:
        expected = render_provider_routes(document, family_path)
    except (OSError, KeyError, ValueError, json.JSONDecodeError,
            RuntimeError) as error:
        return [str(error)]
    try:
        with open(generated_path, encoding="utf-8") as src:
            actual = src.read()
    except OSError as error:
        return [f"cannot read generated provider routes {generated_path}: {error}"]
    if actual != expected:
        return [
            "generated provider routes differ from the route configuration; "
            "run scripts/simd-op-coverage.py --write-provider-routes"
        ]
    return []


def validate_routes(routes, label):
    if not isinstance(routes, list) or not routes:
        raise ValueError(f"{label}: routes must be a non-empty array")
    defaults = [route for route in routes if isinstance(route, dict) and "selector" not in route]
    if len(defaults) != 1:
        raise ValueError(f"{label}: exactly one default route is required")
    selected = {}
    for route in routes:
        if not isinstance(route, dict):
            raise ValueError(f"{label}: route must be an object")
        if set(route) - {"decision", "provider", "selector"}:
            raise ValueError(f"{label}: unsupported route fields")
        _route_cpp(route.get("decision"), route.get("provider"))
        if "selector" not in route:
            continue
        selector = route["selector"]
        if not isinstance(selector, dict):
            raise ValueError(f"{label}: selector must be an object")
        if set(selector) != {"variant", "runtime_targets", "compiler_ranges"}:
            raise ValueError(f"{label}: invalid selector fields")
        if not isinstance(selector["variant"], dict):
            raise ValueError(f"{label}: variant must be an object")
        variant = _variant_cpp(selector)
        targets = selector["runtime_targets"]
        if not isinstance(targets, list) or not targets or any(
                target not in _TARGET_CPP for target in targets):
            raise ValueError(f"{label}: runtime targets must be supported targets")
        if len(targets) != len(set(targets)):
            raise ValueError(f"{label}: duplicate runtime target")
        ranges = selector["compiler_ranges"]
        if not isinstance(ranges, list) or not ranges:
            raise ValueError(f"{label}: compiler ranges must be non-empty")
        for entry in ranges:
            if not isinstance(entry, dict) or set(entry) != {"kind", "min", "max"}:
                raise ValueError(f"{label}: invalid compiler range fields")
            compiler, minimum, maximum = entry["kind"], entry["min"], entry["max"]
            if compiler not in _COMPILER_CPP or type(minimum) is not int or type(maximum) is not int or not (
                    0 <= minimum <= maximum <= 0xffffffff):
                raise ValueError(f"{label}: invalid compiler range")
            for target in targets:
                intervals = selected.setdefault((variant, target, compiler), [])
                if any(minimum <= old_max and old_min <= maximum
                       for old_min, old_max in intervals):
                    raise ValueError(f"{label}: overlapping selector compiler ranges")
                intervals.append((minimum, maximum))


def validate_configuration(document, families, dependency_lock):
    if not isinstance(document, dict) or document.get("schema") != "hyle.simd.operation-routing/v4":
        raise ValueError("unsupported SIMD operation route configuration schema")
    operation_names(document)
    revisions = {row["name"].upper(): row["revision"]
                 for row in dependency_lock["dependencies"]
                 if row["name"] in {"highway", "xsimd"}}
    if document.get("provider_revisions") != revisions:
        raise ValueError("SIMD operation routes do not match locked provider revisions")
    if not isinstance(families, dict) or families.get("schema") != "hyle.simd.family-routing/v2":
        raise ValueError("unsupported SIMD family route configuration schema")
    if families.get("provider_revisions") != revisions:
        raise ValueError("SIMD family routes do not match locked provider revisions")
    for operation in document["operations"]:
        if set(operation) != {"name", "routes"}:
            raise ValueError(f"{operation['name']}: invalid operation configuration fields")
        validate_routes(operation["routes"], operation["name"])
    rows = families.get("families")
    if not isinstance(rows, list) or not rows:
        raise ValueError("SIMD family routes must be a non-empty array")
    names = set()
    for family in rows:
        if not isinstance(family, dict) or set(family) != {"name", "default", "exceptions"}:
            raise ValueError("invalid SIMD family configuration fields")
        name = family["name"]
        if not isinstance(name, str) or re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name) is None or name in names:
            raise ValueError("invalid or duplicate SIMD family name")
        names.add(name)
        exceptions = family["exceptions"]
        if not isinstance(exceptions, list) or any(
                not isinstance(route, dict) or "selector" not in route for route in exceptions):
            raise ValueError(f"{name}: family exceptions must have selectors")
        validate_routes([family["default"], *exceptions], name)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--routes", type=Path, default=OPERATION_ROUTES,
                        help="operation route configuration")
    parser.add_argument("--family-routes", type=Path, default=FAMILY_ROUTES)
    parser.add_argument("--provider-manifest", type=Path, default=PROVIDER_MANIFEST)
    parser.add_argument("--provider-routes", type=Path, default=PROVIDER_ROUTES)
    parser.add_argument("--check", action="store_true", help="check configuration and both generated headers")
    parser.add_argument("--check-provider-manifest", action="store_true")
    parser.add_argument("--check-provider-routes", action="store_true")
    parser.add_argument("--write-provider-manifest", action="store_true")
    parser.add_argument("--write-provider-routes", action="store_true")
    args = parser.parse_args()
    try:
        document = json.loads(args.routes.read_text(encoding="utf-8"))
        families = json.loads(args.family_routes.read_text(encoding="utf-8"))
        lock = json.loads((ROOT / "cmake/HyleDependencyLock.json").read_text(encoding="utf-8"))
        validate_configuration(document, families, lock)
        artifacts = [
            (args.provider_manifest, render_provider_operation_manifest(document),
             args.write_provider_manifest, args.check or args.check_provider_manifest),
            (args.provider_routes, render_provider_routes(document, args.family_routes),
             args.write_provider_routes, args.check or args.check_provider_routes),
        ]
        for path, contents, write, check in artifacts:
            if write:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(contents, encoding="utf-8", newline="\n")
                print(f"wrote {path}")
            if check and path.read_text(encoding="utf-8") != contents:
                raise ValueError(f"generated header differs from route configuration: {path}")
    except (OSError, ValueError, KeyError, TypeError, RuntimeError) as error:
        print(f"SIMD routes: {error}", file=sys.stderr)
        return 1
    print(f"SIMD routes: {len(document['operations'])} operations, {len(families['families'])} families")
    return 0


if __name__ == "__main__":
    sys.exit(main())
