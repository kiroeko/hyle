#!/usr/bin/env python3
"""Capture and validate matched, single-request Hyle/llama prefill profiles.

Use binaries built from sources generated by inference-nsys-prepare.py. The
two fresh processes run sequentially in one window. Both captures must pass
the first-token, workload, capacity, warmup and CUDA-boundary checks before a
comparison is written. This is a diagnostic, not a performance benchmark.
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import importlib.util
import math
from pathlib import Path
import sqlite3
import subprocess
import sys
import time


ROOT = Path(__file__).resolve().parents[1]


def module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    result = importlib.util.module_from_spec(spec)
    sys.modules[name] = result
    spec.loader.exec_module(result)
    return result


compare = module("hyle_profile_consumers", ROOT / "scripts/inference-compare.py")
nsys_compare = module("hyle_profile_boundaries", ROOT / "scripts/inference-nsys-compare.py")


def execute(folder, stage, argv, environment, timeout):
    target = folder / stage
    target.mkdir()
    (target / "command.txt").write_text(subprocess.list2cmdline(argv) + "\n", encoding="utf-8")
    started = time.perf_counter()
    status = "launch_failed"
    try:
        with (target / "stdout.log").open("wb") as stdout, (target / "stderr.log").open("wb") as stderr:
            result = subprocess.run(argv, cwd=ROOT, env=environment, stdout=stdout, stderr=stderr,
                                    timeout=timeout, creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
        status = f"exit={result.returncode}"
        if result.returncode:
            raise RuntimeError(f"{stage} failed; inspect {target}")
    finally:
        (target / "result.txt").write_text(
            f"{status} wall_seconds={time.perf_counter() - started:.6f}\n", encoding="utf-8")


def capture(args, arm, scenario):
    folder = args.output / arm.name
    folder.mkdir()
    command = compare.command(arm, scenario, args)
    trace = folder / "trace"
    profile_command = [str(args.nsys), "profile", "--trace=cuda,cublas,nvtx", "--cuda-graph-trace=node",
                       "--sample=none", "--cpuctxsw=none", "--capture-range=cudaProfilerApi",
                       "--capture-range-end=stop", "--discard-environment=true", "--stop-on-exit=true",
                       "--wait=all", "--stats=false", "--force-overwrite=false", "--output=" + str(trace),
                       *command]
    plan = ["UTC=" + datetime.now(timezone.utc).isoformat(), "version=" + arm.version,
            f"arm={arm.name} mode={args.mtp} capacity={args.capacity} quota={scenario.quotas[0]}",
            "Single diagnostic process; no performance acceptance claim.", subprocess.list2cmdline(profile_command)]
    (folder / "plan.txt").write_text("\n".join(plan) + "\n", encoding="utf-8")
    environment = compare.environment(arm)
    environment["HYLE_DIAGNOSTIC_STDOUT"] = str(folder / "target-stdout.log")
    environment["HYLE_DIAGNOSTIC_STDERR"] = str(folder / "target-stderr.log")
    print(f"Capturing {arm.name}...", flush=True)
    execute(folder, "native", profile_command, environment, args.timeout)
    execute(folder, "export", [str(args.nsys), "export", "--type=sqlite", "--force-overwrite=false",
                               "--output=" + str(folder / "trace.sqlite"), str(trace) + ".nsys-rep"],
            environment, args.timeout)
    sample = nsys_compare.load_profile(folder, "hyle" if arm.hyle else "peer")
    workload = sample[0]
    expected = {"input_ids": scenario.prompts[0], "capacity": args.capacity,
                "mtp": args.mtp == "on", "quota": scenario.quotas[0]}
    nsys_compare.match_workloads(workload, expected)
    (folder / "qualification.txt").write_text(
        "PASS: input, mode, effective capacity, startup warmup, prefill publication, "
        "decode boundary and CUDA activity boundaries.\n", encoding="utf-8")
    return sample


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--nsys", type=Path, required=True)
    parser.add_argument("--hyle", type=Path, required=True, help="Instrumented Hyle consumer")
    parser.add_argument("--reference", type=Path, required=True, help="Instrumented matched reference consumer")
    parser.add_argument("--hyle-version", required=True)
    parser.add_argument("--reference-version", required=True)
    parser.add_argument("--hyle-runtime", type=Path)
    parser.add_argument("--reference-runtime", type=Path)
    parser.add_argument("--model", type=Path, required=True)
    parser.add_argument("--inputs", type=Path, required=True)
    parser.add_argument("--reference-inputs", type=Path, required=True)
    parser.add_argument("--schedule", type=Path, required=True)
    parser.add_argument("--capacity", type=int, required=True)
    parser.add_argument("--mtp", choices=("off", "on"), default="off")
    parser.add_argument("--timeout", type=float, default=900)
    parser.add_argument("--output", type=Path, required=True, help="New directory below .scratch")
    args = parser.parse_args()
    try:
        for name in ("nsys", "hyle", "reference", "hyle_runtime", "reference_runtime", "model",
                     "inputs", "reference_inputs", "schedule", "output"):
            path = getattr(args, name)
            if path is not None:
                setattr(args, name, path.resolve())
        scratch = (ROOT / ".scratch").resolve()
        if not args.output.is_relative_to(scratch) or args.output == scratch or args.output.exists():
            raise ValueError("Output must be a new directory under repository .scratch")
        if not math.isfinite(args.timeout) or args.timeout <= 0 or args.capacity <= 0:
            raise ValueError("Capacity and timeout must be positive")
        for path in (args.nsys, args.hyle, args.reference, args.model, args.schedule):
            if not path.is_file():
                raise ValueError(f"Required local file missing: {path}")
        for path in (args.inputs, args.reference_inputs):
            if not path.is_dir():
                raise ValueError(f"Required local inputs missing: {path}")
        for path in (args.hyle_runtime, args.reference_runtime):
            if path is not None and not path.is_file():
                raise ValueError(f"Runtime receipt missing: {path}")
        scenario = compare.read_schedule(args.schedule)
        if len(scenario.prompts) != 1 or scenario.quotas[0] < 2:
            raise ValueError("Capture requires one prompt and a generation quota of at least 2")
        if len(scenario.prompts[0]) + scenario.quotas[0] > args.capacity:
            raise ValueError("Prompt and requested generation exceed capacity")
        hyle = compare.Arm("hyle", args.hyle, args.hyle_version, args.hyle_runtime, True)
        peer = compare.Arm("reference", args.reference, args.reference_version, args.reference_runtime, False)
        args.output.mkdir(parents=True)
        status = args.output / "status.txt"
        status.write_text("INCOMPLETE\n", encoding="utf-8")
        h = capture(args, hyle, scenario)
        p = capture(args, peer, scenario)
        result = nsys_compare.report(h, p)
        (args.output / "profile-comparison.md").write_text(result, encoding="utf-8")
        status.write_text("COMPLETE: both profiles and the paired comparison passed validation.\n", encoding="utf-8")
        print(result, end="")
    except (OSError, ValueError, KeyError, RuntimeError, sqlite3.Error, subprocess.SubprocessError) as error:
        print(f"inference-nsys-capture: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
