template <typename T>
constexpr std::span<const ScalarLayoutSegment>
scalar_layout(unsigned bits) noexcept {
  static_assert(std::is_same_v<T, std::uint8_t> ||
                std::is_same_v<T, std::uint16_t>);
  if constexpr (std::is_same_v<T, std::uint8_t>) {
    const std::size_t first = kScalarU8Offsets[bits - 1];
    return {kScalarU8Segments + first, kScalarU8Offsets[bits] - first};
  } else {
    const std::size_t first = kScalarU16Offsets[bits - 1];
    return {kScalarU16Segments + first, kScalarU16Offsets[bits] - first};
  }
}

