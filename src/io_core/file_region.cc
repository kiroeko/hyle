constexpr std::uint64_t kLargestFileOffset =
    static_cast<std::uint64_t>((std::numeric_limits<std::int64_t>::max)());
constexpr std::size_t kFallbackBytes = 64u * 1024u;
constexpr std::uint32_t kNativeChunkBytes = 2u * 1024u * 1024u;

Status budget_status(const OperationOptions &options) noexcept {
  if (options.cancel != nullptr && options.cancel->is_cancelled())
    return Status::Cancelled("file-region send cancelled");
  if (options.deadline.has_value() &&
      *options.deadline <= time::monotonic_now())
    return Status::DeadlineExceeded("file-region send deadline expired");
  return {};
}

TransferResult stopped(std::size_t bytes, Status status,
                       bool eof = false) noexcept {
  return TransferResult{bytes, std::move(status), eof};
}

bool unsupported_native_error(std::int64_t native) noexcept {
  if (native >= 0)
    return false;
  const std::uint64_t magnitude = static_cast<std::uint64_t>(-(native + 1)) + 1;
#if HYLE_OS_WINDOWS
  return magnitude == ERROR_INVALID_FUNCTION ||
         magnitude == ERROR_NOT_SUPPORTED || magnitude == WSAEOPNOTSUPP ||
         magnitude == WSAEINVAL;
#else
  return magnitude == EINVAL || magnitude == ENOSYS || magnitude == ENOTSOCK ||
         magnitude == EOPNOTSUPP || magnitude == EXDEV;
#endif
}

