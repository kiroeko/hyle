struct NativeSendFileAwaitable {
  detail::Proactor *proactor = nullptr;
  std::intptr_t socket = -1;
  std::intptr_t file = -1;
  std::uint64_t offset = 0;
  std::uint32_t length = 0;
  mem::AllocatorRef allocator;
  OperationOptions options{};
  detail::BudgetState state{};

  bool await_ready() noexcept {
    state = detail::BudgetState{proactor, allocator, options};
    return state.await_ready();
  }
  bool await_suspend(std::coroutine_handle<>) noexcept {
    return state.await_suspend([&](std::uint64_t token) noexcept {
      return proactor->submit_send_file(socket, file, offset, length, token);
    });
  }
  std::int64_t await_resume() noexcept { return state.await_resume(); }
};

#else

struct WritableAwaitable {
  detail::Proactor *proactor = nullptr;
  std::intptr_t socket = -1;
  mem::AllocatorRef allocator;
  OperationOptions options{};
  detail::BudgetState state{};

  bool await_ready() noexcept {
    state = detail::BudgetState{proactor, allocator, options};
    return state.await_ready();
  }
  bool await_suspend(std::coroutine_handle<>) noexcept {
    return state.await_suspend([&](std::uint64_t token) noexcept {
      return proactor->submit_poll_write(socket, token);
    });
  }
  std::int64_t await_resume() noexcept { return state.await_resume(); }
};

