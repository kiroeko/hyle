Status validate_fallback_alignment(const File &file, std::uint64_t offset,
                                   std::uint64_t length) noexcept {
  if (file.cache_mode() != FileCacheMode::kDirect)
    return {};
  const DirectIoAlignment alignment = file.direct_alignment();
  if (kFallbackBytes % alignment.length_alignment != 0 ||
      offset % alignment.offset_alignment != 0 ||
      length % alignment.length_alignment != 0) {
    return Status::InvalidArgument(
        "direct file region cannot use the bounded fallback alignment");
  }
  return {};
}

