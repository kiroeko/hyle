// sendfile(2) has no MSG_NOSIGNAL argument. Block SIGPIPE only around the
// synchronous syscall, and consume only a signal newly generated by this call.
// No coroutine suspension occurs while the worker thread's mask is changed.
std::int64_t guarded_sendfile(std::intptr_t socket, std::intptr_t file,
                              std::uint64_t offset,
                              std::size_t length) noexcept {
  sigset_t pipe_set;
  sigemptyset(&pipe_set);
  sigaddset(&pipe_set, SIGPIPE);

  sigset_t old_mask;
  const int mask_error = ::pthread_sigmask(SIG_BLOCK, &pipe_set, &old_mask);
  if (mask_error != 0)
    return -static_cast<std::int64_t>(mask_error);

  sigset_t pending_before;
  if (::sigpending(&pending_before) != 0) {
    const int pending_error = errno;
    (void)::pthread_sigmask(SIG_SETMASK, &old_mask, nullptr);
    return -static_cast<std::int64_t>(pending_error);
  }
  const bool had_pending = ::sigismember(&pending_before, SIGPIPE) == 1;

  off_t native_offset = static_cast<off_t>(offset);
  const ssize_t sent = ::sendfile(
      static_cast<int>(socket), static_cast<int>(file), &native_offset, length);
  const int send_error = sent < 0 ? errno : 0;

  if (sent < 0 && send_error == EPIPE && !had_pending) {
    const timespec no_wait{0, 0};
    while (::sigtimedwait(&pipe_set, nullptr, &no_wait) < 0 && errno == EINTR) {
    }
  }
  const int restore_error = ::pthread_sigmask(SIG_SETMASK, &old_mask, nullptr);
  if (sent < 0)
    return -static_cast<std::int64_t>(send_error);
  if (restore_error != 0)
    return -static_cast<std::int64_t>(restore_error);
  return static_cast<std::int64_t>(sent);
}

