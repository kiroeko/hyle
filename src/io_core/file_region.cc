sched::Task<TransferResult>
send_file_region(mem::AllocatorRef allocator, TcpStream &stream, File &file,
                 FileRegion region, OperationOptions options) noexcept {
  if (!allocator.valid())
    co_return stopped(
        0, Status::InvalidArgument("file-region send requires an allocator"));
  if (!stream.valid())
    co_return stopped(
        0, Status::FailedPrecondition("TCP stream is not connected"));
  if (!file.valid())
    co_return stopped(0, Status::FailedPrecondition("file is not open"));
  if (stream.io_ != file.io_ || stream.owner_ != file.owner_)
    co_return stopped(
        0, Status::InvalidArgument(
               "file and TCP stream must share one IoContext owner"));
  if (sched::current_worker_index() != static_cast<int>(stream.owner_))
    co_return stopped(
        0, Status::FailedPrecondition(
               "file-region send must run on the resource owner worker"));
  if (region.offset > kLargestFileOffset ||
      region.length > kLargestFileOffset - region.offset ||
      region.length >
          static_cast<std::uint64_t>((std::numeric_limits<std::size_t>::max)()))
    co_return stopped(0, Status::OutOfRange("file region overflows"));
  if (region.empty())
    co_return TransferResult{};

  Status budget = budget_status(options);
  if (!budget.ok())
    co_return stopped(0, std::move(budget));

  detail::Proactor &proactor =
      detail::IoContextAccess::proactor_for_current(*stream.io_);
  std::size_t done = 0;
  bool use_native = true;

  while (done < static_cast<std::size_t>(region.length) && use_native) {
    budget = budget_status(options);
    if (!budget.ok())
      co_return stopped(done, std::move(budget));
    const std::uint64_t remaining = region.length - done;
    const std::uint32_t chunk = static_cast<std::uint32_t>(
        std::min<std::uint64_t>(remaining, kNativeChunkBytes));

#if HYLE_OS_WINDOWS
    const std::int64_t native =
        co_await NativeSendFileAwaitable{&proactor,
                                         stream.fd_,
                                         file.native_handle(),
                                         region.offset + done,
                                         chunk,
                                         allocator,
                                         options};
#else
    const std::int64_t native = guarded_sendfile(
        stream.fd_, file.native_handle(), region.offset + done, chunk);
    if (native == -EINTR)
      continue;
    if (native == -EAGAIN || native == -EWOULDBLOCK) {
      const std::int64_t ready =
          co_await WritableAwaitable{&proactor, stream.fd_, allocator, options};
      if (ready < 0) {
        TransferResult failed =
            detail::transfer_from_native(ready, detail::kNetworkNativeDomain,
                                         "file-region writable wait", false);
        failed.bytes = done;
        co_return failed;
      }
      continue;
    }
#endif

    if (unsupported_native_error(native)) {
      use_native = false;
      break;
    }
    if (native < 0) {
      TransferResult failed = detail::transfer_from_native(
          native, detail::kNetworkNativeDomain, "file-region send", false);
      failed.bytes = done;
      co_return failed;
    }
    if (native == 0)
      co_return stopped(
          done, Status::DataLoss("EOF before file region was sent"), true);
    if (static_cast<std::uint64_t>(native) > remaining)
      co_return stopped(
          done, Status::Internal("native file send exceeded requested region"));

    done += static_cast<std::size_t>(native);
    if (done < static_cast<std::size_t>(region.length))
      sched::Fiber::yield();
  }

  if (done == static_cast<std::size_t>(region.length))
    co_return TransferResult{done, Status{}, false};

  Status alignment = validate_fallback_alignment(file, region.offset + done,
                                                 region.length - done);
  if (!alignment.ok())
    co_return stopped(done, std::move(alignment));

  const std::size_t scratch_alignment =
      file.cache_mode() == FileCacheMode::kDirect
          ? std::max(file.direct_alignment().memory_alignment,
                     alignof(std::max_align_t))
          : alignof(std::max_align_t);
  detail::StagingBuffer scratch;
  if (!scratch.allocate(allocator, kFallbackBytes, scratch_alignment))
    co_return stopped(done, Status::ResourceExhausted(
                                "file-region fallback allocation failed"));

  while (done < static_cast<std::size_t>(region.length)) {
    budget = budget_status(options);
    if (!budget.ok())
      co_return stopped(done, std::move(budget));
    const std::size_t requested = std::min(
        kFallbackBytes, static_cast<std::size_t>(region.length) - done);
    auto bytes = std::span<std::byte>(static_cast<std::byte *>(scratch.data()),
                                      requested);

    // A blocking-file fallback cannot safely return while its worker still
    // borrows scratch. Check the shared budget before and after retirement;
    // socket waits remain natively cancellable through the original options.
    TransferResult read =
        co_await file.read_some_at(region.offset + done, bytes);
    if (!read.ok()) {
      read.bytes = done;
      co_return read;
    }
    if (read.eof || read.bytes == 0)
      co_return stopped(
          done, Status::DataLoss("EOF before file region was sent"), true);
    if (read.bytes > requested)
      co_return stopped(done,
                        Status::Internal("file read exceeded fallback buffer"));

    budget = budget_status(options);
    if (!budget.ok())
      co_return stopped(done, std::move(budget));

    std::size_t written = 0;
    while (written < read.bytes) {
      TransferResult part = co_await stream.write_some(
          std::span<const std::byte>(bytes.data() + written,
                                     read.bytes - written),
          options);
      written += part.bytes;
      done += part.bytes;
      if (!part.ok()) {
        part.bytes = done;
        co_return part;
      }
      if (part.bytes == 0)
        co_return stopped(
            done,
            Status::Unavailable("file-region write made no forward progress"));
    }
  }

  co_return TransferResult{done, Status{}, false};
}

