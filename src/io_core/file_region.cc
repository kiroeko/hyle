std::int64_t guarded_sendfile(std::intptr_t socket, std::intptr_t file,
                              std::uint64_t offset,
                              std::size_t length) noexcept {
  off_t sent = static_cast<off_t>(length);
  const int result =
      ::sendfile(static_cast<int>(file), static_cast<int>(socket),
                 static_cast<off_t>(offset), &sent, nullptr, 0);
  if (sent > 0)
    return static_cast<std::int64_t>(sent);
  return result == 0 ? 0 : -static_cast<std::int64_t>(errno);
}

