// Test-only model-format preparation. Mirrors the lossless bit layout in
// llama.cpp@4c9233c034fc450dcf34c7c0988aebe6da5cdf1a,
// conversion/base.py::ModelBase.repack_mxfp4_blocks (Kimi and DeepSeek callers).
// No quantization, dense F32 weight materialization, or runtime fallback.
namespace d5_official_fp4_storage {
namespace c = hyle::compute;
namespace sem = d5_qwen38_24t_semantic_fragments;

inline void repack(std::span<const std::uint8_t> packed,
                   std::span<const std::uint8_t> scales,
                   std::span<std::byte> target) {
  if (packed.empty() || packed.size() % 16 != 0 ||
      scales.size() != packed.size() / 16 || target.size() != scales.size() * 17)
    throw std::runtime_error("original FP4 payload/scale extent mismatch");
  for (std::size_t block = 0; block < scales.size(); ++block) {
    target[block * 17] = std::byte{scales[block]};
    for (std::size_t j = 0; j < 16; ++j) {
      const auto shift = (j % 2) * 4;
      const auto lo = (packed[block * 16 + j / 2] >> shift) & 15;
      const auto hi = (packed[block * 16 + (j + 16) / 2] >> shift) & 15;
      target[block * 17 + 1 + j] = std::byte(lo | (hi << 4));
    }
  }
}

inline bool matches_original_converter() {
  // Generated by executing the pinned Python function itself on two rows of
  // 64 elements. Zero/special scale bytes and signed codes stay bit-identical;
  // this check does not claim finite arithmetic for exceptional scale values.
  constexpr std::array<std::uint8_t, 68> expected{
      0, 59, 48, 128, 83, 213, 117, 42, 167, 127, 201, 196, 236, 25, 30, 110, 48,
      127, 59, 133, 128, 168, 213, 202, 42, 252, 127, 30, 196, 49, 25, 99, 110, 133,
      254, 59, 218, 128, 253, 213, 31, 42, 65, 127, 99, 196, 134, 25, 184, 110, 218,
      255, 59, 47, 128, 66, 213, 100, 42, 150, 127, 184, 196, 219, 25, 13, 110, 47};
  std::array<std::uint8_t, 64> packed{};
  for (std::size_t i = 0; i < packed.size(); ++i)
    packed[i] = std::uint8_t((i * 37 + 11) % 256);
  constexpr std::array<std::uint8_t, 4> scales{0, 127, 254, 255};
  std::array<std::byte, 68> actual{};
  repack(packed, scales, actual);
  return std::equal(actual.begin(), actual.end(), expected.begin(),
                    [](std::byte a, std::uint8_t b) { return a == std::byte{b}; });
}

inline sem::Weight weight(std::int64_t experts, std::int64_t n, std::int64_t k,
                           int seed) {
  auto desc = c::gguf_grouped_weight_description(c::GgufQuantizedType::kMxfp4,
                  c::DataType::kFloat32, experts, n, k).value();
  sem::Weight result{desc, std::vector<std::byte>(desc.required_bytes().value()),
      std::vector<std::vector<std::pair<std::size_t, float>>>(experts * n)};
  std::vector<std::uint8_t> packed(k / 2), scales(k / 32);
  constexpr std::array<float, 8> e2m1{0, 0.5F, 1, 1.5F, 2, 3, 4, 6};
  const auto row_bytes = std::size_t(k / 32 * 17);
  for (std::int64_t row = 0; row < experts * n; ++row) {
    std::fill(packed.begin(), packed.end(), 0);
    for (std::size_t block = 0; block < scales.size(); ++block)
      scales[block] = std::uint8_t(122 + (row + block + seed) % 3);
    for (int term = 0; term < 2; ++term) {
      const auto col = std::size_t((17 * row + seed + term * (k / 2 + 17)) % k);
      const auto code = std::uint8_t(1 + (row + seed + term * 3) % 7 +
                                    ((row + term) % 2) * 8);
      packed[col / 2] |= std::uint8_t(code << ((col % 2) * 4));
      // Oracle decodes the original source code/scale, never target bytes.
      const auto sign = code & 8 ? -1.0F : 1.0F;
      const float value = std::ldexp(sign * e2m1[code & 7], int(scales[col / 32]) - 127);
      result.decoded[row].emplace_back(col, value);
    }
    repack(packed, scales, std::span(result.storage).subspan(row * row_bytes, row_bytes));
  }
  return result;
}
} // namespace d5_official_fp4_storage
